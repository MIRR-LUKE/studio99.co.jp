import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';

await mkdir('docs/qa/motion', { recursive: true });
const browser = await chromium.launch({ channel: 'chrome' });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, recordVideo: { dir: 'docs/qa/motion', size: { width: 1440, height: 900 } } });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
await page.goto('http://127.0.0.1:3000');
await page.locator('[data-ready="true"]').waitFor();
await page.waitForFunction(()=>document.documentElement.dataset.opticalAtlasCount==='14');
await page.waitForTimeout(3000);
await page.screenshot({ path: 'docs/qa/motion/floating-a.png' });
await page.waitForTimeout(4000);
await page.screenshot({ path: 'docs/qa/motion/floating-b.png' });
await page.mouse.move(276,438);await page.waitForTimeout(180);
await page.screenshot({path:'docs/qa/motion/hover-rebound.png'});
await page.waitForTimeout(1500);await page.mouse.move(1200,160);
await page.keyboard.down('a');
await page.waitForTimeout(90);
await page.screenshot({path:'docs/qa/motion/pressed.png'});
await page.keyboard.up('a');await page.waitForTimeout(250);
await page.screenshot({path:'docs/qa/motion/rebound.png'});
await page.keyboard.press('Escape');
await page.keyboard.type('about', { delay: 140 });
await page.waitForTimeout(1000);
await page.screenshot({ path: 'docs/qa/motion/enter-to-open.png' });
await page.keyboard.press('Enter');
await page.waitForTimeout(420);
await page.screenshot({ path: 'docs/qa/motion/departure.png' });
await page.waitForURL('**/about');
await page.waitForTimeout(700);
await page.screenshot({ path: 'docs/qa/motion/about.png' });
await page.keyboard.press('Escape');
await page.waitForTimeout(1800);
await page.screenshot({ path: 'docs/qa/motion/reassembled.png' });
const video = page.video();
await context.close();
await video.saveAs('docs/qa/motion/keyboard-motion.webm');
await video.delete();
const performancePage=await browser.newPage({viewport:{width:1440,height:900}});
await performancePage.goto('http://127.0.0.1:3000');
await performancePage.waitForFunction(()=>document.documentElement.dataset.opticalAtlasCount==='14');await performancePage.waitForTimeout(2000);
const stats=await performancePage.evaluate(async()=>{
  const frames=[];let previous=performance.now();
  for(let i=0;i<180;i++){const now=await new Promise(resolve=>requestAnimationFrame(resolve));frames.push(now-previous);previous=now;}
  frames.sort((a,b)=>a-b);
  return {averageFps:1000/(frames.reduce((a,b)=>a+b,0)/frames.length),p95FrameMs:frames[Math.floor(frames.length*.95)],...document.documentElement.dataset};
});
await performancePage.close();
const mobileContext=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:2,isMobile:true,hasTouch:true});
const mobile=await mobileContext.newPage();await mobile.goto('http://127.0.0.1:3000');
await mobile.waitForFunction(()=>document.documentElement.dataset.opticalAtlasCount==='14');await mobile.waitForTimeout(1200);
await mobile.screenshot({path:'docs/qa/motion/mobile.png'});await mobileContext.close();
await browser.close();
await writeFile('docs/qa/motion/browser-errors.json', JSON.stringify(errors));
await writeFile('docs/qa/motion/performance.json',JSON.stringify(stats,null,2));
console.log(JSON.stringify({errors,stats,video:'docs/qa/motion/keyboard-motion.webm'}));
